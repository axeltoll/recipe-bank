// Writes site/data/showcase.js: the sample recipes the public site (site/) shows in its interactive showcase.
// The site is a separate static folder, so it cannot read recipes/ at runtime; this script copies the fields
// the page renders, unchanged, from the real recipe files. Run `npm run site:data` after editing one of the
// showcased recipes; test/site-data.test.mjs fails when the committed copy is out of date.
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { validateRecipe } from '../lib/recipe.mjs';

const ROOT = resolve(import.meta.dirname, '..');

/** Recipes shown on the site, in display order. The first one is open when the page loads. */
export const SHOWCASE_IDS = ['cold-pan-chicken', 'air-fried-chicken-nuggets', 'banana-milk'];
export const OUT_FILE = join(ROOT, 'site', 'data', 'showcase.js');

/** The subset of a recipe the site renders. Absent optional fields become null so the shape is fixed. */
export function slimRecipe(r) {
  return {
    id: r.id,
    title: r.title,
    status: r.status,
    video: { platform: r.video.platform, id: r.video.id ?? null, url: r.video.url },
    creator: { name: r.creator.name, handle: r.creator.handle ?? null, url: r.creator.url ?? null },
    summary: r.summary,
    serves: r.serves ?? null,
    tags: r.tags,
    components: r.components.map((c) => ({
      name: c.name,
      ingredients: c.ingredients.map((i) => ({
        item: i.item, key: i.key, amount: i.amount ?? null, basis: i.basis, note: i.note ?? null,
      })),
      steps: c.steps.map((s) => ({ text: s.text, t: s.t ?? null })),
    })),
    nutrition: r.nutrition
      ? {
          per: r.nutrition.per,
          basis: r.nutrition.basis,
          calories: r.nutrition.calories ?? null,
          protein_g: r.nutrition.protein_g ?? null,
          carbs_g: r.nutrition.carbs_g ?? null,
          fat_g: r.nutrition.fat_g ?? null,
          note: r.nutrition.note ?? null,
        }
      : null,
    gaps: r.gaps ?? [],
  };
}

/** Reads the showcased recipes from recipes/ and returns them in site shape. Throws on an invalid recipe. */
export async function buildShowcase(ids = SHOWCASE_IDS) {
  const out = [];
  for (const id of ids) {
    const r = JSON.parse(await readFile(join(ROOT, 'recipes', `${id}.json`), 'utf8'));
    const errs = validateRecipe(r, id);
    if (errs.length) throw new Error(`recipes/${id}.json is not valid: ${errs.join('; ')}`);
    out.push(slimRecipe(r));
  }
  return out;
}

export function renderModule(data) {
  return [
    '// Generated by scripts/build-site-data.mjs from recipes/*.json. Do not edit by hand: run `npm run site:data`.',
    '// The recipes are the repository\'s own files; each one credits and links its creator.',
    `export default ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === import.meta.filename) {
  const data = await buildShowcase();
  await writeFile(OUT_FILE, renderModule(data));
  console.log(`site/data/showcase.js: ${data.length} recipes (${data.map((r) => r.id).join(', ')})`);
}
